// nomad-design's `Sym`, cut down to the marks this site draws.
//
// nomad-design/src/symbols.tsx imports every icon family the design system
// can paint (Iconsax, Iconly, Material, the drawn net: ~1.5 MB). Every
// control that can show a glyph imports it, so a page with one Button would
// ship all of it. This plugin answers nomad-design's own `../symbols` import
// with a module generated from nomad-design's sources at build time: the
// same exports, the same route (Iconsax by name where nomad-design maps one,
// Material for the rest), and only the names in SITE_MARKS.
//
// Add a name here when a page starts drawing it. A name that is not here is
// loud in dev (console.error and the magenta box, as in nomad-design) and
// draws nothing in a build.
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

export const SITE_MARKS = ['caretDown', 'caretRight', 'download', 'globe', 'check', 'menu', 'close', 'display', 'lock', 'account', 'cloud', 'search', 'mail', 'send', 'clock', 'shield', 'eye', 'unlock', 'folder', 'document', 'devices', 'layers', 'share', 'storage', 'seekSnapshot', 'seekGuest', 'driftLink', 'driftDevice', 'driftPerson', 'camera', 'home', 'sliders', 'grid', 'image', 'play', 'pause', 'back', 'forward', 'refresh', 'plus', 'more', 'copy', 'convert', 'music', 'trash', 'settings', 'edit'];

const ND = fileURLToPath(new URL('../../nomad-design/src/', import.meta.url));
const ID = '\0nd-symbols';

/** `name: 'Component'` pairs from iconsaxMap.ts, minus NO_ICONSAX. */
function iconsaxMap() {
  const src = readFileSync(ND + 'iconsaxMap.ts', 'utf8');
  const head = src.slice(src.indexOf('ICONSAX_MAP'), src.indexOf('NO_ICONSAX ='));
  const map = Object.fromEntries([...head.matchAll(/^\s+([A-Za-z0-9]+): '([A-Za-z0-9]+)'/gm)].map((m) => [m[1], m[2]]));
  const no = src.slice(src.indexOf('NO_ICONSAX ='));
  const banned = new Set([...no.slice(0, no.indexOf('];')).matchAll(/^\s+'([A-Za-z0-9]+)'/gm)].map((m) => m[1]));
  for (const b of banned) delete map[b];
  return map;
}

/** One entry of MATERIAL_MARKS, lifted verbatim. */
function materialMark(name) {
  const src = readFileSync(ND + 'materialMarks.ts', 'utf8');
  const start = src.search(new RegExp(`^  ${name}: \\{`, 'm'));
  if (start < 0) return null;
  const end = src.indexOf('\n  },', start);
  return src.slice(start + `  ${name}: `.length, end + 4);
}

function generate() {
  const ix = iconsaxMap();
  const imports = [];
  const libs = [];
  const mats = [];
  for (const name of SITE_MARKS) {
    const comp = ix[name];
    if (comp) {
      // two names can share one drawing (display and driftDevice are both Monitor): import it once
      const line = `import ${comp} from 'iconsax-react/dist/esm/${comp}.js';`;
      if (!imports.includes(line)) imports.push(line);
      libs.push(`  ${name}: ${comp},`);
      continue;
    }
    const mark = materialMark(name);
    if (!mark) throw new Error(`[nd-symbols] "${name}" is neither mapped to Iconsax nor in MATERIAL_MARKS`);
    mats.push(`  ${name}: ${mark},`);
  }
  return `// Generated by tools/nd-symbols.mjs from nomad-design's own maps.
import { jsx } from 'react/jsx-runtime';
${imports.join('\n')}

const LIB = {
${libs.join('\n')}
};
const MAT = {
${mats.join('\n')}
};
const ALWAYS_LINE = ['back', 'forward', 'refresh', 'search', 'caretLeft', 'caretRight', 'caretUp', 'caretDown'];
const DEV = Boolean(import.meta.env && import.meta.env.DEV);
const said = new Set();

export const SYM_NAMES = ${JSON.stringify(SITE_MARKS)};
export function symbolExists(name) { return name in LIB || name in MAT; }

export function Sym({ name, size = 15, variant = 'Linear', className, style }) {
  size = Math.round(size / 2) * 2 || 2;
  const Lib = LIB[name];
  if (Lib) return jsx(Lib, { className, style, variant, color: 'currentColor', size, 'aria-hidden': true });
  const m = MAT[name];
  if (m) {
    const fill = (variant === 'Bold' || variant === 'Bulk' || variant === 'TwoTone') && m.fill && !ALWAYS_LINE.includes(name);
    const d = fill ? m.fill : m.d;
    return jsx('svg', {
      className, style, width: size, height: size, viewBox: m.box, fill: 'currentColor', 'aria-hidden': true, focusable: 'false',
      children: d.map((p, i) => jsx('path', { d: p }, i)),
    });
  }
  if (DEV && !said.has(name)) {
    said.add(name);
    console.error('[Sym] "' + name + '" is not in SITE_MARKS (tools/nd-symbols.mjs).');
  }
  return DEV ? jsx('span', { style: { display: 'inline-block', width: size, height: size, border: '1px dashed #f0f' } }) : null;
}
`;
}

/**
 * Vite plugin: nomad-design's `../symbols` import resolves here.
 * @returns {import('vite').Plugin}
 */
export function ndSymbols() {
  const nd = ND.replace(/\\/g, '/').toLowerCase();
  return {
    name: 'nd-symbols',
    enforce: 'pre',
    resolveId(source, importer) {
      /* The site's own `@nd/symbols` arrives here already aliased to an
         absolute path; nomad-design's controls ask for `../symbols`. */
      const abs = source.replace(/\\/g, '/').toLowerCase();
      if (abs === `${nd}symbols` || abs === `${nd}symbols.tsx`) return ID;
      if (!importer || !/^\.\.?\/symbols(\.tsx)?$/.test(source)) return null;
      const from = importer.replace(/\\/g, '/').toLowerCase();
      return from.startsWith(nd) ? ID : null;
    },
    load(id) {
      return id === ID ? generate() : null;
    },
  };
}
